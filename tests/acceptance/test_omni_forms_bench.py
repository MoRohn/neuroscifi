# ---- the hard constraints, by hand ---------------------------------------------------------------------------------

def _case(device="console", access="", seconds=60.0, kb=8192, n=10, sets=None, rest="unfit"):
    c = forms_cases.K("x", "test", [forms_cases.S("series", n=n)],
                      forms_cases.X(device, access, seconds=seconds, kb=kb), good="prose | r")
    if sets:
        for name, fs in sets.items():
            c["sets"][name] = {"forms": tuple(fs.split()), "reason": "r"}
    c["rest"] = rest
    return c


def test_forms_hard_constraints_by_hand():
    assert forms.violation("line_chart", _case("voice"))                       # no picture on a speaker
    assert forms.violation("prose", _case("voice")) is None                   # prose can be spoken
    assert forms.violation("table", _case("cli")) is None and forms.violation("bar_chart", _case("cli"))
    assert forms.violation("animation", _case(access="reduced_motion"))
    assert forms.violation("step_through", _case(access="reduced_motion")) is None
    assert forms.violation("sonification", _case(access="no_sound"))
    assert forms.violation("line_chart", _case("pocket", access="voice_only"))
    assert forms.violation("line_chart", _case(access="screen_reader"))      # a picture alone
    assert forms.violation("line_chart+prose", _case(access="screen_reader")) is None
    assert forms.violation("sonification", _case(access="screen_reader")) is None
    # budget: a chart's floor is 3,072 bytes; a table's 200 + 8 per value
    assert forms.violation("line_chart", _case(kb=2))
    assert forms.violation("table", _case(kb=2, n=100)) is None               # 1,000 bytes
    assert forms.violation("table", _case(kb=0.5, n=100))                     # over 512
    assert forms.violation("prose", _case(seconds=0.0)) is None and forms.violation("spoken", _case(seconds=0.1))


def test_forms_labels_and_the_combination_rule_by_hand():
    c = _case(sets={"good": "line_chart", "fine": "table", "poor": "prose", "much": "explorable", "unfit": "map"},
              rest="unfit")
    assert forms.label(c, "line_chart")[0] == "good" and forms.label(c, {"form": "LINE_CHART "})[0] == "good"
    assert forms.label(c, "table")[0] == "fine"
    assert forms.label(c, "prose")[0] == "too_poor" and forms.label(c, "explorable")[0] == "too_much"
    assert forms.label(c, "heatmap")[0] == "unfit"                            # not listed: the case's rest
    assert forms.label(c, "no_such_form")[0] == "unfit" and forms.label(c, "")[0] == "unfit"
    assert forms.label(c, "prose+line_chart")[0] == "fine"                    # good carries, poor captions
    assert forms.label(c, "line_chart+table")[0] == "fine"
    assert forms.label(c, "explorable+line_chart")[0] == "too_much"
    assert forms.label(c, "line_chart+map")[0] == "too_much"                  # good plus the wrong kind
    assert forms.label(c, "prose+map")[0] == "unfit"
    assert forms.label(c, "prose+spoken")[0] == "unfit"                      # too_poor with an unlisted (unfit) part
    listed = _case(sets={"good": "line_chart+prose"})
    assert forms.label(listed, "prose + line_chart")[0] == "good"            # order does not matter
    much = _case(rest="much")
    assert forms.label(much, "heatmap")[0] == "too_much"
    assert forms.label(_case("voice"), "line_chart")[0] == "violation"


# ---- scoring on built subjects ---------------------------------------------------------------------------------------

def _bad_form(task):
    case = task.case
    for name in ("poor", "much", "unfit"):
        if case["sets"][name]["forms"]:
            return case["sets"][name]["forms"][0]
    for f in forms.FORMS:                       # the rest label (never good or fine), or a violation
        if forms.label(case, f)[0] not in ("good", "fine"):
            return f
    raise AssertionError(task.id)


@pytest.mark.parametrize("split", forms.SPLITS)
def test_forms_scoring_extremes(split):
    perfect = forms.score("first_good", split)
    assert perfect["good"]["share"] == 1.0 and perfect["bad"]["k"] == 0
    assert perfect["hard_constraints_violated"]["k"] == 0
    assert perfect["explicit"]["feasible_honoured"]["share"] == 1.0
    assert perfect["explicit"]["infeasible_handled"]["share"] == 1.0
    assert perfect["pairs"]["pair"]["share"] == 1.0 and perfect["pairs"]["twin"]["share"] == 1.0
    lookup = {t.id: t for t in forms.tasks(split)}
    worst = forms.score(lambda view: _bad_form(lookup[view["id"]]), split)
    assert worst["good"]["k"] == 0 and worst["good_or_fine"]["k"] == 0 and worst["bad"]["share"] == 1.0


