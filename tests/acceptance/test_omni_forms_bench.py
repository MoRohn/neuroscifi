DEVICES = {"console", "pocket", "voice", "cli", "agent"}


def _sha(module):
    return hashlib.sha256(Path(module.__file__).read_bytes()).hexdigest()


def _all():
    return [c for split in forms.SPLITS for c in forms_cases.ALL[split]]


# ---- the freeze ----------------------------------------------------------------------------------------------------

def test_forms_cases_are_frozen():
    assert _sha(forms_cases) == FORMS_CASES_SHA256


def test_cross_cases_and_generated_bytes_are_frozen():
    assert _sha(cross_cases) == CROSS_CASES_SHA256
    for split in cross.SPLITS:
        assert cross.digest(split) == CROSS_GENERATED_SHA256[split], split


def test_learn_people_are_frozen():
    assert _sha(learn_people) == LEARN_PEOPLE_SHA256


MINE = ("forms.py", "forms_cases.py", "cross.py", "cross_cases.py", "learn.py", "learn_people.py")


def test_lane_zf_modules_import_no_product_code():
    """Standard library and sibling modules only: no `neuroscifi.*`, no relative import that leaves the package."""
    folder = Path(forms.__file__).parent
    for name in MINE:
        path = folder / name
        if not path.exists():
            continue
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Import):
                assert not any(a.name.split(".")[0] == "neuroscifi" for a in node.names), name
            elif isinstance(node, ast.ImportFrom):
                assert node.level in (0, 1), name
                assert node.level == 1 or (node.module or "").split(".")[0] != "neuroscifi", name


