def test_forms_counts_and_coverage():
    stats = forms.table_stats()
    for split in forms.SPLITS:
        s = stats[split]
        assert s["cases"] >= 120
        assert s["prose_right"] * 3 >= s["cases"] and s["prose_alone_right"] * 3 >= s["cases"]
        assert set(s["content_kinds"]) == KINDS                         # every content kind, in each split
        assert set(s["devices"]) == DEVICES                              # every device, in each split
        assert s["explicit"] >= 10 and s["explicit_infeasible"] >= 3 and s["explicit_less"] >= 3
        assert {"screen_reader", "voice_only", "reduced_motion", "no_sound"} <= set(s["access"])
        assert s["budget"] >= 3 and s["ex72"] >= 5 and s["counter72"] >= 5
    assert stats["development"]["pairs"] + stats["held_out"]["pairs"] >= 30


def test_forms_splits_are_disjoint_and_ids_unique():
    ids = [c["id"] for c in _all()]
    assert len(ids) == len(set(ids))
    dev = {c["request"].lower() for c in forms_cases.DEVELOPMENT}
    held = {c["request"].lower() for c in forms_cases.HELD_OUT}
    assert not dev & held and len(dev) == len(forms_cases.DEVELOPMENT) and len(held) == len(forms_cases.HELD_OUT)


def test_forms_every_judgement_is_well_formed():
    for c in _all():
        assert {k for s in c["content"] for k in s["kinds"]} <= KINDS, c["id"]
        assert c["context"]["device"] in DEVICES, c["id"]
        assert c["sets"]["good"]["forms"], c["id"]
        listed = []
        for name, entry in c["sets"].items():
            assert bool(entry["forms"]) == bool(entry["reason"]) or (not entry["forms"] and c["rest"] == name), \
                (c["id"], name)
            for f in entry["forms"]:
                assert all(p in forms.FORMS for p in forms.norm(f).split("+")), (c["id"], f)
                listed.append(forms.norm(f))
        assert len(listed) == len(set(listed)), c["id"]                  # no form in two sets
        cue = [t for t in c["tags"] if t in ("content", "words", "conflict", "explicit")]
        assert len(cue) == 1, c["id"]
        assert ("explicit" in c["tags"]) == bool(c["explicit"]), c["id"]


def test_forms_good_and_fine_never_break_a_hard_constraint():
    for c in _all():
        for name in ("good", "fine"):
            for f in c["sets"][name]["forms"]:
                assert forms.violation(f, c) is None, (c["id"], name, f, forms.violation(f, c))


def test_forms_a_feasible_explicit_form_is_good_and_an_infeasible_one_is_not_listed():
    infeasible = 0
    for c in _all():
        if not c["explicit"]:
            continue
        good_parts = {p for f in c["sets"]["good"]["forms"] for p in forms.norm(f).split("+")}
        if forms.explicit_feasible(c):
            assert c["explicit"] in good_parts, c["id"]
        else:
            infeasible += 1
            # the form alone is not good; with a text part it may be (a screen reader user's diagram, h069)
            assert c["explicit"] not in {forms.norm(f) for f in c["sets"]["good"]["forms"]}, c["id"]
            assert forms.label(c, c["explicit"])[0] == "violation", c["id"]
    assert infeasible >= 6


def test_forms_pairs_share_cue_words_and_differ_in_answer():
    groups = {}
    for split in forms.SPLITS:
        for c in forms_cases.ALL[split]:
            if c["pair"]:
                groups.setdefault(c["pair"][0], []).append((split, c))
    assert len(groups) >= 30
    for pid, members in groups.items():
        assert len(members) == 2 and members[0][0] == members[1][0], pid              # same split
        (_, a), (_, b) = members
        assert a["pair"][1] == b["pair"][1]
        for c in (a, b):
            assert a["pair"][1].lower() in c["request"].lower(), (pid, c["id"])       # the cue words in both
        assert a["content"] != b["content"], pid                                     # the content differs
        ga = {forms.norm(f) for f in a["sets"]["good"]["forms"]}
        gb = {forms.norm(f) for f in b["sets"]["good"]["forms"]}
        assert not ga & gb, pid                                                       # the right answers differ


def test_forms_twins_share_content_and_context_and_differ_in_answer():
    groups = {}
    for split in forms.SPLITS:
        for c in forms_cases.ALL[split]:
            if c["twin"]:
                groups.setdefault(c["twin"], []).append((split, c))
    assert len(groups) >= 15
    for tid, members in groups.items():
        assert len(members) == 2 and members[0][0] == members[1][0], tid
        (_, a), (_, b) = members
        assert a["content"] == b["content"] and a["context"] == b["context"], tid
        assert not {forms.norm(f) for f in a["sets"]["good"]["forms"]} & \
            {forms.norm(f) for f in b["sets"]["good"]["forms"]}, tid


