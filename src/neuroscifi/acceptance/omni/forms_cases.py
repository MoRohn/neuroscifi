"""OMNIMIND benchmark, family `forms`: the case tables (development and held-out), written by hand one case at a time.

FROZEN: tests/acceptance/test_omni_forms_bench.py pins this file's SHA-256. Changing a case makes every earlier number
incomparable; add cases in a new file instead. Data only: nothing here imports product code, and nothing here is
derived from a list of verbs or from the planner's tables (there are none yet; the planner's author must not read
this file to write rules).

A case is a person's request in their own words, the shapes of the content the system has for it (DESIGN section 2
`ContentShape`, as plain dicts), the context (device, what it can show, accessibility needs, stated preferences,
budget), optionally the form the person named (`explicit`) and a purpose, and the examiner's judgement in five sets,
each with a one-line reason:

  good       forms that serve the person well
  fine       forms that are acceptable
  poor       forms that are too poor for the content (too_poor: three paragraphs for 365 daily values)
  much       forms that are too much for the question (too_much: a simulation for the boiling point of water)
  unfit      forms of the wrong kind for the content (a node-link diagram for a temperature series)

"*" in a set's forms makes that set's label the label of every form the case does not list (default: unfit). A form
the context cannot carry is a hard violation whatever the sets say (forms.py decides that from the context).

Form names are the benchmark's own vocabulary (forms.py FORMS); "a+b" is a combination of two.

Tags: the cue type (exactly one of `content`: the content's shape and the context decide, the words give no cue to
the form; `words`: the words decide; `conflict`: the words point one way and the content another; `explicit`: the
person named a form), and any of `less` (an explicit request for less than the content could support), `access`,
`budget`, `prefs`, `ex72` (one of the directive's section 7.2 examples), `counter72` (the same kind of topic where a
sentence suffices). `pair` = (id, cue words): two cases sharing the cue words whose right answers differ because the
content differs. `twin` = id: two cases with the same content and context whose right answers differ because the
words differ.
"""
from __future__ import annotations

_SCREEN = "text picture sound interaction motion 3d file"
_SHOWS = {"console": _SCREEN, "pocket": _SCREEN, "voice": "sound", "cli": "text file", "agent": "text file"}
_SETS = ("good", "fine", "poor", "much", "unfit")


def S(kinds, n=1, series=1, time=False, space=0, params=False, dur=0.0, chars=0):
    """A ContentShape as a plain dict."""
    return {"kinds": tuple(kinds.split()), "n_items": n, "n_series": series, "has_time": time, "has_space": space,
            "has_parameters": params, "duration_s": float(dur), "text_chars": chars}


def X(device, access="", prefer="", avoid="", seconds=60.0, kb=8192, shows=None):
    """A context: the device, what it can show (the device's default unless given), accessibility needs, the stated
    preferences (soft), and the budget (seconds, bytes)."""
    return {"device": device, "shows": tuple(sorted((shows or _SHOWS[device]).split())),
            "access": tuple(access.split()), "prefer": tuple(prefer.split()), "avoid": tuple(avoid.split()),
            "budget": {"seconds": float(seconds), "bytes": int(kb * 1024)}}


def K(cid, request, content, context, *, ask=None, purpose=None, good, fine="", poor="", much="", unfit="", tags="",
      pair=None, twin=None):
    sets, rest = {}, "unfit"
    for name, text in zip(_SETS, (good, fine, poor, much, unfit)):
        forms, _, reason = text.partition(" | ")
        names = tuple(forms.split())
        if "*" in names:
            rest = name
            names = tuple(f for f in names if f != "*")
        sets[name] = {"forms": names, "reason": reason.strip()}
    return {"id": cid, "request": request, "explicit": ask, "purpose": purpose, "content": tuple(content),
            "context": context, "sets": sets, "rest": rest, "tags": tuple(tags.split()), "pair": pair, "twin": twin}


